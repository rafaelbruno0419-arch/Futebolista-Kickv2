// Dados astronômicos reais (J2000). Distâncias em km, tempos em dias.
// Elementos orbitais: JPL Approximate Positions of the Major Planets.

export type BodyKind = 'star' | 'planet' | 'moon' | 'dwarf' | 'comet'
export type SurfaceType = 'sun' | 'rocky' | 'earth' | 'gas' | 'ice-giant' | 'venus' | 'icy'

export interface Orbit {
  a: number // semi-eixo maior (AU)
  e: number // excentricidade
  i: number // inclinação (graus)
  L: number // longitude média em J2000 (graus)
  peri: number // longitude do periélio (graus)
  node: number // longitude do nó ascendente (graus)
  period: number // período orbital (dias)
}

export interface BodyDef {
  id: string
  name: string
  kind: BodyKind
  parent: string | null
  radius: number // km
  surface: SurfaceType
  orbit: Orbit | null
  rotation: number // período de rotação em horas (negativo = retrógrado)
  tilt: number // obliquidade em graus
  color: string // cor do marcador/rótulo
  mass: string
  gravity: string
  temp: string
  day: string
  year: string
  moons: string
  discovered: string
  fact: string
  // parâmetros de shader
  p: {
    seed: number
    colA: [number, number, number]
    colB: [number, number, number]
    colC: [number, number, number]
    craters?: number
    albedoVar?: number
    bands?: number
    turb?: number
    ice?: number
    rough?: number
    atmo?: [number, number, number]
    atmoStrength?: number
    clouds?: number
  }
  rings?: { inner: number; outer: number; tilt?: number; opacity?: number }
}

